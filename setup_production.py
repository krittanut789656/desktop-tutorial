def check_database_setup(host, port, user, password, database):
    """Verify database setup"""
    try:
        import mysql.connector

        conn = mysql.connector.connect(
            host=host,
            port=port,
            user=user,
            password=password,
            database=database
        )
        cursor = conn.cursor()

        # Check tables
        cursor.execute("SHOW TABLES")
        tables = [row[0] for row in cursor.fetchall()]

        expected_tables = ['etfs', 'daily_prices', 'portfolios', 'portfolio_etfs',
                          'backtests', 'backtest_transactions', 'backtest_portfolio_values',
                          'backtest_metrics']

        missing_tables = [t for t in expected_tables if t not in tables]

        # Check ETFs
        cursor.execute("SELECT COUNT(*) FROM etfs")
        etf_count = cursor.fetchone()[0]

        # Check price data
        cursor.execute("SELECT COUNT(*) FROM daily_prices")
        price_count = cursor.fetchone()[0]

        # Check portfolios
        cursor.execute("SELECT COUNT(*) FROM portfolios")
        portfolio_count = cursor.fetchone()[0]

        cursor.close()
        conn.close()

        return {
            'success': len(missing_tables) == 0,
            'tables': tables,
            'missing_tables': missing_tables,
            'etf_count': etf_count,
            'price_count': price_count,
            'portfolio_count': portfolio_count
        }

    except Exception as e:
        return {'success': False, 'error': str(e)}

