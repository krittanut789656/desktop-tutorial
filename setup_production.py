    print("\nSteps:")
    print("  1. Test MySQL connection")
    print("  2. Create database and tables")
    print("  3. Insert sample data (40 ETFs, 8 portfolios)")
    print("  4. Install Python dependencies")
    print("  5. Create configuration file")
    print("  6. Run data collection (fetch ETF prices 2009-2025)")
    print("  7. Verify setup")
    print("  8. Ready to run!")

    input(f"\n{Colors.YELLOW}Press Enter to continue...{Colors.END}")

    # =========================================================================
    # STEP 1: Get MySQL credentials
    # =========================================================================
    print_header("STEP 1: MySQL Connection Setup")

    host = input(f"{Colors.CYAN}MySQL Host [127.0.0.1]: {Colors.END}").strip() or "127.0.0.1"
    port = input(f"{Colors.CYAN}MySQL Port [3306]: {Colors.END}").strip() or "3306"
    port = int(port)
    user = input(f"{Colors.CYAN}MySQL User [root]: {Colors.END}").strip() or "root"
    password = getpass.getpass(f"{Colors.CYAN}MySQL Password: {Colors.END}")
    database = "etf_backtesting"

    print_info(f"Testing connection to {user}@{host}:{port}...")
    success, error = test_mysql_connection(host, port, user, password)

    if not success:
        print_error(f"MySQL connection failed: {error}")
        print_warning("Please check your credentials and MySQL server status")
        sys.exit(1)

    print_success("MySQL connection successful!")

    # =========================================================================
    # STEP 2: Install dependencies
    # =========================================================================
    print_header("STEP 2: Installing Python Dependencies")

    print_info("This may take a few minutes...")
    success, error = install_dependencies()

    if not success:
        print_warning("Some dependencies may have failed to install")
        print_warning(f"Error: {error}")
        print_info("Continuing anyway... You may need to install manually later")
    else:
        print_success("All dependencies installed successfully!")

    # =========================================================================
    # STEP 3: Create database and tables
    # =========================================================================
    print_header("STEP 3: Creating Database and Tables")

    sql_files = [
        ('database/01_create_database.sql', None, 'Database and tables'),
        ('database/02_insert_sample_etfs.sql', database, '40 Sample ETFs'),
        ('database/03_insert_sample_portfolios.sql', database, '8 Sample portfolios')
    ]

    for sql_file, db, description in sql_files:
        if os.path.exists(sql_file):
            print_info(f"Creating {description}...")
            success, error = run_sql_file(sql_file, host, port, user, password, db)

            if success:
                print_success(f"{description} created successfully!")
            else:
                print_error(f"Failed to create {description}: {error}")
                if "01_create_database" in sql_file:
                    print_error("Cannot continue without database. Exiting.")
                    sys.exit(1)
        else:
            print_warning(f"SQL file not found: {sql_file}")

    # =========================================================================
    # STEP 4: Create config file
    # =========================================================================
    print_header("STEP 4: Creating Configuration File")

    success, error = create_config_file(host, port, user, password, database)

    if success:
        print_success("config.ini created successfully!")
    else:
        print_warning(f"Failed to create config.ini: {error}")
        print_info("You can create it manually later")

    # =========================================================================
    # STEP 5: Verify database setup
    # =========================================================================
    print_header("STEP 5: Verifying Database Setup")

    status = check_database_setup(host, port, user, password, database)

    if status.get('success'):
        print_success("Database setup verified!")
        print(f"\n{Colors.CYAN}Database Statistics:{Colors.END}")
        print(f"  Tables: {len(status['tables'])}/8")
        print(f"  ETFs: {status['etf_count']}")
        print(f"  Price Records: {status['price_count']:,}")
        print(f"  Portfolios: {status['portfolio_count']}")

        if status['missing_tables']:
            print_warning(f"Missing tables: {', '.join(status['missing_tables'])}")
    else:
        print_error(f"Database verification failed: {status.get('error', 'Unknown error')}")

    # =========================================================================
    # STEP 6: Data collection
    # =========================================================================
    print_header("STEP 6: ETF Price Data Collection")

    if status.get('price_count', 0) > 10000:
        print_info(f"Price data already exists ({status['price_count']:,} records)")
        run_collection = input(f"{Colors.YELLOW}Re-fetch price data? This will take 10-15 minutes (y/n): {Colors.END}").strip().lower()
    else:
        run_collection = 'y'
        print_info("No price data found. Will fetch historical prices...")

    if run_collection == 'y':
        print_info("Fetching historical prices for 40+ ETFs (2009-2025)...")
        print_warning("This will take approximately 10-15 minutes")
        print_info("You can monitor progress in another terminal:")
        print(f"  {Colors.CYAN}tail -f data_collection/data_collection.log{Colors.END}")

        proceed = input(f"\n{Colors.YELLOW}Start data collection now? (y/n): {Colors.END}").strip().lower()

        if proceed == 'y':
            try:
                # Change to data_collection directory
                original_dir = os.getcwd()
                os.chdir('data_collection')

                print_info("Starting data collection...")
                result = subprocess.run(
                    [sys.executable, "data_collection.py"],
                    timeout=1200  # 20 minute timeout
                )

                os.chdir(original_dir)

                if result.returncode == 0:
                    print_success("Data collection completed!")
                else:
                    print_warning("Data collection may have encountered issues")
                    print_info("Check data_collection/data_collection.log for details")

            except subprocess.TimeoutExpired:
                print_warning("Data collection timed out (20 minutes)")
                print_info("You can run it manually later: cd data_collection && python data_collection.py")
            except Exception as e:
                print_warning(f"Data collection error: {e}")
                print_info("You can run it manually later: cd data_collection && python data_collection.py")
        else:
            print_info("Skipping data collection")
            print_warning("Run manually later: cd data_collection && python data_collection.py")

    # =========================================================================
    # FINAL VERIFICATION
    # =========================================================================
    print_header("FINAL VERIFICATION")

    final_status = check_database_setup(host, port, user, password, database)

