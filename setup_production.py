import os
import sys
import subprocess
import getpass
from pathlib import Path

# Colors for output
class Colors:
    GREEN = '\033[92m'
    RED = '\033[91m'
    YELLOW = '\033[93m'
    CYAN = '\033[96m'
    BOLD = '\033[1m'
    END = '\033[0m'

def print_header(message):
    """Print formatted header"""
    print(f"\n{Colors.BOLD}{Colors.CYAN}{'='*80}")
    print(f"{message.center(80)}")
    print(f"{'='*80}{Colors.END}\n")

def print_success(message):
    """Print success message"""
    print(f"{Colors.GREEN}✓ {message}{Colors.END}")

def print_error(message):
    """Print error message"""
    print(f"{Colors.RED}✗ {message}{Colors.END}")

def print_warning(message):
    """Print warning message"""
    print(f"{Colors.YELLOW}⚠ {message}{Colors.END}")

def print_info(message):
    """Print info message"""
    print(f"{Colors.CYAN}ℹ {message}{Colors.END}")

def test_mysql_connection(host, port, user, password):
    """Test MySQL connection"""
    try:
        import mysql.connector
        conn = mysql.connector.connect(
            host=host,
            port=port,
            user=user,
            password=password
        )
        conn.close()
        return True, None
    except ImportError:
        return False, "mysql-connector-python not installed. Run: pip install mysql-connector-python"
    except Exception as e:
        return False, str(e)

def run_sql_file(file_path, host, port, user, password, database=None):
    """Execute SQL file"""
    try:
        import mysql.connector

        connect_params = {
            'host': host,
            'port': port,
            'user': user,
            'password': password
        }

        if database:
            connect_params['database'] = database

        conn = mysql.connector.connect(**connect_params)
        cursor = conn.cursor()

        # Read and execute SQL file
        with open(file_path, 'r', encoding='utf-8') as f:
            sql_script = f.read()

        # Split by semicolon and execute each statement
        statements = sql_script.split(';')
        for statement in statements:
            statement = statement.strip()
            if statement:
                try:
                    cursor.execute(statement)
                except Exception as e:
                    # Some statements might fail (like DROP IF EXISTS on non-existent tables)
                    # Only show error if it's not a "doesn't exist" error
                    if "doesn't exist" not in str(e).lower():
                        print_warning(f"SQL Warning: {str(e)[:100]}")

        conn.commit()
        cursor.close()
        conn.close()
        return True, None

    except Exception as e:
        return False, str(e)

def install_dependencies():
    """Install Python dependencies"""
    try:
        print_info("Installing Python dependencies...")
        result = subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", "requirements.txt"],
            capture_output=True,
            text=True,
            timeout=300
        )

        if result.returncode == 0:
            return True, None
        else:
            return False, result.stderr

    except Exception as e:
        return False, str(e)

